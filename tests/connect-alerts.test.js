'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const read=name=>fs.readFileSync(path.join(ROOT,name),'utf8');
test('Cricket Connect notifications are enabled across subscribed app pages only',()=>{
 const shell=read('fluent-shell.js');
 assert.match(shell,/available\.communications===true/);
 assert.match(shell,/void startConnectAlerts\(\)/);
 assert.match(shell,/await loadScript\('connect-alerts\.js'\)/);
 assert.match(shell,/page!=='connect\.html'/,'Connect owns its own signaling stream');
 assert.match(read('connect.html'),/src="connect-alerts\.js"/);
 assert.match(read('connect.html'),/src="sound-engine\.js"/);
 assert.match(read('connect.js'),/CricketConnectAlerts\?\.handle\(packet\)/);
 assert.match(read('connect.js'),/CricketConnectAlerts\?\.startDial/);
 const modules=read('server/modules.js');
 assert.match(modules,/\/connect-alerts\.js':'communications'/);
 assert.match(modules,/\/connect-alerts\.css':'communications'/);
 const server=read('server/server.js');
 assert.match(server,/\/connect-alerts\.js',\['agent','qc','admin'\]/);
 assert.match(server,/\/connect-alerts\.css',\['agent','qc','admin'\]/);
});
test('Connect ringtone, dial tone and message sounds follow employee sound preferences',()=>{
 const alerts=read('connect-alerts.js'),sounds=read('sound-engine.js');
 assert.match(alerts,/new EventSource\('\/api\/connect\/events'\)/);
 assert.match(alerts,/window\.CricketSound\?\.play/);
 assert.match(alerts,/connect-incoming/);
 assert.match(alerts,/connect-ringback/);
 assert.match(alerts,/connect-text/);
 assert.match(alerts,/connect-ended/);
 assert.match(alerts,/Notification\.requestPermission/);
 assert.match(alerts,/CricketConnectAlerts=/);
 assert.match(alerts,/message\(packet\)/);
 assert.match(alerts,/function call\(packet\)/);
 assert.match(alerts,/if\(!isConnect\)popup/);
 assert.match(sounds,/contextForPlayback\(type\)/);
 assert.match(sounds,/settings\.enabled/);
 assert.match(sounds,/connect-incoming/);
 assert.match(sounds,/connect-ringback/);
 assert.match(sounds,/connect-text/);
 assert.doesNotMatch(alerts,/https?:\/\/|WebSocket\(/,'Alerts should not depend on external service URLs');
});
test('Local Windows HTTPS setup keeps private credentials in ignored data directory and never disables TLS checks',()=>{
 const script=read('start-lan-https.ps1');
 const server=read('server/server.js');
 assert.match(script,/New-SelfSignedCertificate/);
 assert.match(script,/IPAddress=\$LanIP/);
 assert.match(script,/Export-PfxCertificate/);
 assert.match(script,/ConvertFrom-SecureString/);
 assert.match(script,/data\\certs/);
 assert.match(script,/cricket-lan\.cer/);
 assert.match(script,/Thumbprint/);
 assert.match(script,/Trusted Root Certification Authorities/);
 assert.doesNotMatch(script,/NODE_TLS_REJECT_UNAUTHORIZED|--ignore-certificate-errors|curl.*-k/i);
 assert.match(read('.gitignore'),/data\//);
 assert.match(server,/https\.createServer\(tlsOptions, requestHandler\)/);
 assert.match(server,/req\.socket\.encrypted/);
 assert.match(server,/COOKIE_SECURE/);
 assert.match(server,/CRICKET_TLS_PFX/);
});
